/* Фонове відео, яке не заважає першому екрану.

   Декоративне відео важить сотні кілобайт і на повільній мережі забирає смугу саме тоді,
   коли браузер тягне шрифти й розмітку — тобто відсуває момент, коли видно текст. А сам
   текст на нього не чекає й чекати не має.

   Тому елемент з'являється лише після того, як сторінка вже намальована: спершу браузер
   доводить до кінця критичну роботу, і тільки потім у справу йде фон.

   Друге, що тут вирішується — зеленуватий кадр у прев'ю вікна. Повноекранне відео Chrome
   виносить в апаратний оверлей: окрему площину GPU повз звичайний композитинг. Виграш у
   декодуванні є, але композитор Windows такої площини не бачить, і в мініатюрі на панелі
   завдань (та в перші кадри після повернення у вікно) на її місці лишається службовий
   колір — той самий зелений. Ненульова прозорість змушує браузер змішувати відео зі
   сторінкою у звичайний спосіб, тож в оверлей воно не потрапляє. Різниці в 0.1% яскравості
   не видно, а прев'ю стає нормальним. */

import { useIdle } from "@/shared/lib/useIdle";

type DeferredVideoProps = {
  src: string;
  className?: string;
};

const DeferredVideo = ({ src, className }: DeferredVideoProps) => {
  const ready = useIdle();

  if (!ready) return null;

  return (
    <video
      src={src}
      autoPlay
      loop
      muted
      playsInline
      // Показувати керуємо ми, а не браузер: до появи елемента запиту взагалі немає.
      preload="auto"
      className={className}
      aria-hidden="true"
      style={{ opacity: 0.999 }}
    />
  );
};

export default DeferredVideo;
